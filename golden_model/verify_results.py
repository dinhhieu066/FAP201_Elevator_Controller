"""
Verification Script (FAP201 Project)
Author: FAP201 Student
Description:
    Compares the simulation outputs generated by the Verilog RTL Testbench
    (rtl_output.txt) against the Golden Model expected outputs (golden_output.txt).
    Generates a full equivalence report.
"""

import os
import sys

def verify():
    base_dir = os.path.dirname(os.path.abspath(__file__))
    project_dir = os.path.abspath(os.path.join(base_dir, ".."))
    tb_dir = os.path.join(project_dir, "testbench")

    golden_file = os.path.join(tb_dir, "golden_output.txt")
    rtl_file = os.path.join(tb_dir, "rtl_output.txt")

    if not os.path.exists(golden_file):
        print(f"[ERROR] Golden file not found: {golden_file}")
        return False

    if not os.path.exists(rtl_file):
        print(f"[ERROR] RTL output file not found: {rtl_file}")
        print("Please run the RTL simulation first (e.g., using ModelSim) to produce rtl_output.txt.")
        return False

    def load_lines(filepath):
        data = []
        with open(filepath, "r") as f:
            for line in f:
                line = line.strip()
                if not line or line.startswith("#"):
                    continue
                parts = [int(p) for p in line.split()]
                data.append(parts)
        return data

    golden_data = load_lines(golden_file)
    rtl_data = load_lines(rtl_file)

    print("=========================================================================")
    print("         FAP201 - RTL VS GOLDEN MODEL EQUIVALENCE CHECKER                ")
    print("=========================================================================")
    print(f"Golden vector count : {len(golden_data)}")
    print(f"RTL vector count    : {len(rtl_data)}")

    mismatches = []
    min_len = min(len(golden_data), len(rtl_data))

    field_names = ["current_floor", "state", "door_open", "direction", "pending_req"]

    for cycle in range(min_len):
        g = golden_data[cycle]
        r = rtl_data[cycle]
        if g != r:
            diff_fields = []
            for i, name in enumerate(field_names):
                if g[i] != r[i]:
                    diff_fields.append(f"{name}: Gold={g[i]} vs RTL={r[i]}")
            mismatches.append((cycle, diff_fields))

    if len(golden_data) != len(rtl_data):
        print(f"[WARNING] Vector count mismatch: Golden has {len(golden_data)}, RTL has {len(rtl_data)} cycles!")

    if not mismatches and len(golden_data) == len(rtl_data):
        print("\n*************************************************************************")
        print("   [PASSED] 100% MATCH! ALL SIGNALS MATCH GOLDEN MODEL EXACTLY!          ")
        print(f"   Total verified cycles: {min_len} cycles")
        print("*************************************************************************\n")
        return True
    else:
        print(f"\n[FAILED] Found {len(mismatches)} cycle mismatches:")
        for cycle, diffs in mismatches[:15]:
            print(f"  Cycle {cycle:4d}: {', '.join(diffs)}")
        if len(mismatches) > 15:
            print(f"  ... and {len(mismatches) - 15} more mismatches.")
        print("*************************************************************************\n")
        return False

if __name__ == "__main__":
    verify()
